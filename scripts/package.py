"""Assemble the complete installed runtime; preserve Unix modes in the ZIP."""
from pathlib import Path
import hashlib, json, shutil, stat, sys, zipfile
root = Path(__file__).resolve().parent.parent
build = root / 'build'
pkg = build / 'package' / 'mkxp-z.pak'
runtime = build / 'mkxp-z'
assert (runtime/'bin/mkxp-z').is_file(), 'build mkxp-z first'
if pkg.exists(): shutil.rmtree(pkg)
shutil.copytree(root/'pak', pkg)
shutil.copytree(runtime, pkg/'emulators/mkxp-z', dirs_exist_ok=True)
# Installed development archives and pkg-config files are not runtime assets.
for directory in ('include','lib'):
    shutil.rmtree(pkg/'emulators/mkxp-z'/directory,ignore_errors=True)
# The device firmware supplies fmt 9; the SDK links against fmt 10.
shutil.copytree(build/'runtime-libs', pkg/'emulators/mkxp-z/lib')
# Keep only the stable executable name in bin/.
for old in (pkg/'emulators/mkxp-z').glob('mkxp-z.*'):
    if old.is_file(): old.unlink()
# The invocation config is generated by launch.sh, never read from the pak.
(pkg/'emulators/mkxp-z/mkxp.json').unlink(missing_ok=True)
for p in [pkg/'emulators/mkxp-z/launch.sh', pkg/'emulators/mkxp-z/bin/mkxp-z']:
    p.chmod(0o755)
shutil.copy2(root/'docs/PROVENANCE.md',pkg/'PROVENANCE.md')
shutil.copy2(root/'README.md',pkg/'README.md')
shutil.copy2(build/'binary-report.json',pkg/'binary-report.json')
dist=build/'dist'; dist.mkdir(exist_ok=True)
archive=dist/'mkxp-z.mlp1.pak.zip'
with zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED) as z:
    for p in sorted(pkg.rglob('*')):
        if not p.is_file(): continue
        name=p.relative_to(pkg.parent).as_posix()
        info=zipfile.ZipInfo(name,(2026,11,1,0,0,0))
        info.create_system=3
        mode=0o755 if p.name in ('launch.sh','mkxp-z') else 0o644
        info.external_attr=(stat.S_IFREG | mode)<<16
        info.compress_type=zipfile.ZIP_DEFLATED
        z.writestr(info,p.read_bytes())
print(archive)
print('SHA256',hashlib.sha256(archive.read_bytes()).hexdigest())
